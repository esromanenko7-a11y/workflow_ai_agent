def validate_catalog() -> None:
    """
    Проверяет целостность каталога.

    Такая проверка похожа на контроль справочника:
    количество правил ожидаемо, коды уникальны,
    обязательные поля заполнены.
    """

    expected_count = 28

    if len(VALIDATION_CATALOG) != expected_count:
        raise ValueError(
            "Некорректное количество проверок: "
            f"получено {len(VALIDATION_CATALOG)}, "
            f"ожидалось {expected_count}."
        )

    codes = [rule.code for rule in VALIDATION_CATALOG]

    if len(codes) != len(set(codes)):
        raise ValueError(
            "В каталоге обнаружены повторяющиеся коды проверок."
        )

    for rule in VALIDATION_CATALOG:
        if not rule.code.strip():
            raise ValueError("Обнаружено правило без кода.")

        if not rule.name.strip():
            raise ValueError(
                f"У правила {rule.code} отсутствует название."
            )

        if not rule.verification.strip():
            raise ValueError(
                f"У правила {rule.code} отсутствует описание."
            )

        if rule.severity not in {"FATAL", "ERROR", "WARNING"}:
            raise ValueError(
                f"У правила {rule.code} указан неизвестный "
                f"уровень критичности: {rule.severity}."
            )


validate_catalog()